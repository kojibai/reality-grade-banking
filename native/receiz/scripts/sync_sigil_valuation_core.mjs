import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

// The application's established vφ-5 implementation is the only math source.
// Copy its pure calculator seam byte-for-byte; do not fork SDK or MCP math.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const canonicalPath = resolve(root, 'app/utils/valuation.ts');
const outputPath = resolve(root, 'packages/receiz-sdk/src/sigilValuationCore.ts');
const canonical = readFileSync(canonicalPath, 'utf8');
const seam = '/** Build a full ValueSeal by hashing the canonical payload with the provided hasher. */';
if (canonical.indexOf(seam) < 0 || canonical.indexOf(seam) !== canonical.lastIndexOf(seam)) {
  throw new Error('Canonical intrinsic valuation extraction seam is missing or ambiguous');
}
const body = canonical.slice(0, canonical.indexOf(seam));
const source = ts.createSourceFile(canonicalPath, body, ts.ScriptTarget.Latest, true);
if (source.statements.some(node => ts.isImportDeclaration(node) || ts.isImportEqualsDeclaration(node))) {
  throw new Error('Canonical calculator gained an import; review browser/Node offline safety before synchronizing');
}
const generated = '// Generated by scripts/sync_sigil_valuation_core.mjs from app/utils/valuation.ts.\n'
  + '// Do not edit this copy. The application calculator is canonical.\n\n' + body;
const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : null;
if (process.argv.includes('--check')) {
  if (current !== generated) throw new Error('SDK intrinsic calculator differs from canonical application source; run node scripts/sync_sigil_valuation_core.mjs');
} else if (current !== generated) writeFileSync(outputPath, generated);
console.log('Canonical Kai-sigil valuation extraction aligned.');
