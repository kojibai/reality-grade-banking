import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { execFileSync } from "node:child_process";

// Packaging mechanics only: canonical artifacts and frozen generated TypeScript
// stay byte-identical. Emitted readers reuse their exact frozen predecessor laws.
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const artifacts = resolve(root, "../../docs/releases");
for (let version = 115; version <= 125; version++) {
  const read = (v) => JSON.parse(readFileSync(resolve(artifacts, `v${v}.0.0-constitution-registry.json`), "utf8"));
  const prior = read(version - 1);
  const current = read(version);
  const digest = readFileSync(resolve(artifacts, `v${version}.0.0-constitution-registry.digest`), "utf8").trim();
  const emittedPath = resolve(root, `dist/v${version}Registry.generated.js`);
  assert.ok(readFileSync(emittedPath, "utf8").includes(digest), "compiled registry must bind its canonical digest");
  const fields = Object.fromEntries(Object.entries(current).filter(([key, value]) => key !== "laws" && JSON.stringify(value) !== JSON.stringify(prior[key])));
  const changed = Object.fromEntries(current.laws.filter(law => JSON.stringify(law) !== JSON.stringify(prior.laws.find(item => item.id === law.id))).map(law => [law.id, law]));
  const ids = current.laws.map(law => law.id);
  writeFileSync(emittedPath, `// Exact canonical registry projection; generated by compact-registry-projections.mjs.\nimport { RECEIZ_V${version - 1}_CONSTITUTION_REGISTRY as previous } from "./v${version - 1}Registry.generated.js";\nfunction freeze(value) { if (value && typeof value === "object" && !Object.isFrozen(value)) { for (const child of Object.values(value)) freeze(child); Object.freeze(value); } return value; }\nconst changed = ${JSON.stringify(changed)};\nconst inherited = new Map(previous.laws.map(law => [law.id, law]));\nexport const RECEIZ_GENERATED_V${version}_REGISTRY_DIGEST = ${JSON.stringify(digest)};\nexport const RECEIZ_V${version}_CONSTITUTION_REGISTRY = freeze({ ...previous, ...${JSON.stringify(fields)}, laws: ${JSON.stringify(ids)}.map(id => changed[id] ?? inherited.get(id)) });\nexport function loadReceizV${version}Registry() { return freeze(structuredClone(RECEIZ_V${version}_CONSTITUTION_REGISTRY)); }\n`);
}

// A fresh process prevents import caching from validating the pre-compaction
// modules. Compare every property and verify with the existing digest primitive.
execFileSync(process.execPath, ["--input-type=module", "-e", `
  import assert from "node:assert/strict";
  import { readFileSync } from "node:fs";
  import { digestReceizConstitution } from "./dist/constitution.js";
  for (let version = 115; version <= 127; version++) {
    const module = await import('./dist/v' + version + 'Registry.generated.js');
    const expected = JSON.parse(readFileSync('../../docs/releases/v' + version + '.0.0-constitution-registry.json', 'utf8'));
    const registry = module['RECEIZ_V' + version + '_CONSTITUTION_REGISTRY'];
    assert.deepEqual(registry, expected);
    assert.equal(await digestReceizConstitution(registry), module['RECEIZ_GENERATED_V' + version + '_REGISTRY_DIGEST']);
    assert.ok(Object.isFrozen(registry) && Object.isFrozen(registry.laws));
    const detached = module['loadReceizV' + version + 'Registry']();
    assert.deepEqual(detached, expected);
    assert.notEqual(detached, registry);
    assert.notEqual(detached.laws, registry.laws);
  }
`], { cwd: root, stdio: "inherit" });
console.log("Registry package projections preserve all v115–v127 canonical bytes, digests and detached frozen readers.");
